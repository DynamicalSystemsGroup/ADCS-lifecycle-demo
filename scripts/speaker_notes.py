"""Companion speaker notes: one file, in slide order, for the speaker only.

The slides carry almost no text; the story lives in each talk module's ``## Speaker notes``
section (``private/talk/modules/*.md``). This script concatenates them in deck order, taking the
order from the ``SLIDE:Sx`` and ``BEAT:Bn`` markers in ``talk.py`` (first occurrence of each), and
writes ``private/talk/speaker_notes.md``. A module that owns several slides appears once, at its
first slide. A beat's note is the line that starts with its id (``B2: ...``) in a module's notes.

The private directory is gitignored and may be absent: then this prints a message and exits 0.

Usage:
    uv run python scripts/speaker_notes.py
    uv run python scripts/speaker_notes.py --private ../elsewhere/private
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import typer

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))  # so that `python scripts/speaker_notes.py` finds the package

from scripts.talk_check import parse_module  # noqa: E402
MARKER = re.compile(r"(?:SLIDE:(S\d+)|BEAT:(B\d+))")

app = typer.Typer(add_completion=False, help=__doc__.splitlines()[0])


def deck_order(notebook: Path) -> list[str]:
    """Slide and beat ids in file order, each once."""
    seen: list[str] = []
    for m in MARKER.finditer(notebook.read_text()):
        i = m.group(1) or m.group(2)
        if i not in seen:
            seen.append(i)
    return seen


def notes_section(body: str) -> str:
    """The text under ``## Speaker notes``, up to the next ``## `` heading."""
    m = re.search(r"^## Speaker notes\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return m.group(1).strip() if m else ""


def build(notebook: Path, modules_dir: Path) -> str:
    mods = {}
    for path in sorted(modules_dir.glob("S*.md")):
        mod = parse_module(path)
        mods[mod.id] = (mod, notes_section(mod.body))
    parts = ["# Speaker notes\n\nGenerated by scripts/speaker_notes.py in slide order; do not edit.\n"]
    for sid in deck_order(notebook):
        if sid.startswith("S") and sid in mods:
            mod, notes = mods[sid]
            parts.append(f"## {sid} · {mod.path.stem.split('-', 1)[-1].replace('-', ' ')}\n\n{notes or '_no notes_'}\n")
            continue
        if sid.startswith("B"):
            line = next(
                (ln for _, notes in mods.values() for ln in notes.splitlines() if re.match(rf"{sid}\b", ln)),
                None,
            )
            parts.append(f"## {sid}\n\n{line or '_no notes_'}\n")
    return "\n".join(parts)


@app.command()
def main(
    private: Path = typer.Option(ROOT / "private", help="the private directory"),
    notebook: Path = typer.Option(ROOT / "talk.py", help="the notebook that carries the markers"),
) -> None:
    modules_dir = private / "talk" / "modules"
    if not modules_dir.is_dir():
        typer.echo(f"No private modules at {modules_dir}: nothing to write.")
        raise typer.Exit(0)
    out = private / "talk" / "speaker_notes.md"
    out.write_text(build(notebook, modules_dir))
    typer.echo(f"Wrote {out}")


if __name__ == "__main__":
    app()
